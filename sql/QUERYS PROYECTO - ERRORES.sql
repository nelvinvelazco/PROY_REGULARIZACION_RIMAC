    SELECT *, ROW_NUMBER() OVER (PARTITION BY COD_DE_CERTIFICADO, FEC__INICIO, FEC__FIN) AS NRO
    FROM (
          SELECT DISTINCT *
          FROM `produccion.ERRORES_desgravamen_prestamos_BBVA` 
        )
    WHERE COD_DE_CERTIFICADO != 'nan' AND MONEDA != 'SIN DATO'
)
SELECT COD_DE_CERTIFICADO, FEC__INICIO, FEC__FIN, PRIMABRUTACAN, 
        REGEXP_REPLACE(LINEA_TRAMA, r'[^\x20-\x7E\n\r]|\t', ' ') AS TRAMA_LIMPIA
FROM tabla_prestamos
WHERE TIPO_SEGURO NOT IN ('901', '902', '903', '906',
                          '958', '968', '972') AND IDEERROR != '1106'
      AND TIPO_MOVIMIENTO = 'Inclusion' AND NRO= 1 AND
      COD_DE_CERTIFICADO NOT IN (
        SELECT DISTINCT *
        FROM `produccion.cert_errores_acsele-02-09`
      )
ORDER BY COD_DE_CERTIFICADO, FEC__INICIO, FEC__FIN


