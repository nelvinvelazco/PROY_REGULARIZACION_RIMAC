WITH TOTALES AS(
  SELECT MONEDA, COUNT(*) AS CANT, SUM(PRIMABRUTACAN) AS TOTAL_PRIMA, 
        CASE 
            WHEN MONEDA = 'SOL' THEN SUM(PRIMABRUTACAN) / 3.4
            ELSE SUM(PRIMABRUTACAN)
        END AS DOLARIZADO
  FROM `produccion.ERRORES_BBVA_primas` P
  LEFT JOIN `produccion.Tabla_Errores_SAS_v2` E ON P.IDEERROR= E.IDEERROR
  WHERE P.TIPO_MOVIMIENTO = 'Endoso'
  GROUP BY MONEDA
)
SELECT SUM(DOLARIZADO) AS TOTAL_DOLARIZADO
FROM TOTALES 


