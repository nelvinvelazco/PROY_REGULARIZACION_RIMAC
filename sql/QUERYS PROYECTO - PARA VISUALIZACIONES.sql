SELECT CODIGO_PRODUCTO, CODIGO_CERTIFICADO, FECHA_CARGA, 
        CASE WHEN CODIGO_ERROR IS NULL THEN ' ' 
              ELSE CODIGO_ERROR
        END AS CODIGO_ERROR, 
        FECHA_INICIO, FECHA_FIN, PRIMA_BRUTA, MONEDA,
        TIPO_MOVIMIENTO, ORIGEN_ERROR, CODIGO_SEGURO, CODIGO_MOVIMIENTO,
        ROW_NUMBER() OVER (PARTITION BY CODIGO_CERTIFICADO, FECHA_INICIO, FECHA_FIN) AS NRO,
        #CASE WHEN CODIGO_PRODUCTO = '3189' THEN
        #          ROW_NUMBER() OVER (PARTITION BY NUM_DOCUMENTO, FECHA_INICIO, FECHA_FIN)
        #      ELSE
        #           ROW_NUMBER() OVER (PARTITION BY CODIGO_CERTIFICADO, FECHA_INICIO, FECHA_FIN)
        #END AS NRO,
        COUNT(*) OVER (PARTITION BY CODIGO_CERTIFICADO) AS CANT_ERRORES,
        ROW_NUMBER() OVER (PARTITION BY CODIGO_CERTIFICADO ORDER BY FECHA_INICIO ASC, FECHA_FIN ASC) AS ORDEN
