        SELECT DISTINCT *
        FROM `produccion.ERRORES_prestamos_temp` 
)
WHERE CODIGO_CERTIFICADO IS NOT NULL



#======================= ERRORES DE PRODUCTOS BANCA SEGUROS -----------------------

CREATE OR REPLACE TABLE `produccion.ERRORES_BS_todos` AS
WITH varios_prods AS(
    SELECT CODIGO_PRODUCTO, CODIGO_CERTIFICADO, FECHA_CARGA, 
        CODIGO_ERROR, FECHA_INICIO, FECHA_FIN, PRIMA_BRUTA, MONEDA,
        TIPO_MOVIMIENTO, ORIGEN_ERROR, CODIGO_SEGURO, CODIGO_MOVIMIENTO
    FROM (
        SELECT DISTINCT *
        FROM `produccion.ERRORES_prestamos_temp` 
        WHERE CODIGO_CERTIFICADO IS NOT NULL AND CODIGO_PRODUCTO NOT IN ('7791','6321')  
    )
),
onco_Efectiva AS (
    SELECT CAST(CODIGO_PRODUCTO AS STRING) AS CODIGO_PRODUCTO, COD_DE_CERTIFICADO AS CODIGO_CERTIFICADO, FECHA_CARGA, E.CODERROR AS CODIGO_ERROR,
            DATE(FEC__INICIO) AS FECHA_INICIO, DATE(FEC__FIN) AS FECHA_FIN, PRIMABRUTACAN AS PRIMA_BRUTA, MONEDA,
            TIPO_MOVIMIENTO, ORIGEN_ERROR, TIPO_SEGURO AS CODIGO_SEGURO, TIPO_MOVIMIENTO_NUM AS CODIGO_MOVIMIENTO                     
    FROM (
        SELECT DISTINCT *
        FROM `produccion.ERRORES_BS_efectiva_ieg_onco` 
        WHERE COD_DE_CERTIFICADO IS NOT NULL
    ) T
    LEFT JOIN `produccion.Tabla_Errores_SAS_v2` E ON T.IDEERROR= E.IDEERROR
),
desgravamen_ripley AS (
    SELECT '6321' AS CODIGO_PRODUCTO, COD_DE_CERTIFICADO AS CODIGO_CERTIFICADO, FECHA_CARGA, E.CODERROR AS CODIGO_ERROR,
            DATE(FEC__INICIO) AS FECHA_INICIO, DATE(FEC__FIN) AS FECHA_FIN, PRIMABRUTACAN AS PRIMA_BRUTA, MONEDA,
            TIPO_MOVIMIENTO, ORIGEN_ERROR, TIPO_SEGURO AS CODIGO_SEGURO, TIPO_MOVIMIENTO_NUM AS CODIGO_MOVIMIENTO  
    FROM (
        SELECT DISTINCT *
        FROM `produccion.ERRORES_BS_desgravamen_RIPLEY` 
        WHERE COD_DE_CERTIFICADO IS NOT NULL
    ) T
    LEFT JOIN `produccion.Tabla_Errores_SAS_v2` E ON T.IDEERROR= E.IDEERROR
)
SELECT CODIGO_PRODUCTO, CODIGO_CERTIFICADO, FECHA_CARGA, 
        CASE WHEN CODIGO_ERROR IS NULL THEN ' ' 
              ELSE CODIGO_ERROR
        END AS CODIGO_ERROR, 
        FECHA_INICIO, FECHA_FIN, PRIMA_BRUTA, MONEDA,
        TIPO_MOVIMIENTO, ORIGEN_ERROR, CODIGO_SEGURO, CODIGO_MOVIMIENTO,
        ROW_NUMBER() OVER (PARTITION BY CODIGO_CERTIFICADO, FECHA_INICIO, FECHA_FIN) AS NRO,
        #CASE WHEN CODIGO_PRODUCTO = '3189' THEN
        #          ROW_NUMBER() OVER (PARTITION BY NUM_DOCUMENTO, FECHA_INICIO, FECHA_FIN)
        #      ELSE
        #           ROW_NUMBER() OVER (PARTITION BY CODIGO_CERTIFICADO, FECHA_INICIO, FECHA_FIN)
        #END AS NRO,
        COUNT(*) OVER (PARTITION BY CODIGO_CERTIFICADO) AS CANT_ERRORES,
        ROW_NUMBER() OVER (PARTITION BY CODIGO_CERTIFICADO ORDER BY FECHA_INICIO ASC, FECHA_FIN ASC) AS ORDEN
FROM (
        SELECT * FROM varios_prods
        UNION ALL
        SELECT * FROM onco_Efectiva
        UNION ALL
        SELECT * FROM desgravamen_ripley 
)
WHERE CODIGO_CERTIFICADO IS NOT NULL