CREATE OR REPLACE TABLE `produccion.ERRORES_BN_temp` AS
WITH ERROR_BN AS(
    SELECT CODIGO_PRODUCTO, substr(LINEA_TRAMA, 28, 20) AS CODIGO_CERTIFICADO, FECHA_CARGA, NUMDOCUMENTO,
            CASE WHEN IDEERROR IS NULL THEN ' ' 
                    ELSE IDEERROR
            END AS IDEERROR, 
            FEC__INICIO AS FECHA_INICIO, FEC__FIN AS FECHA_FIN, PRIMABRUTACAN AS PRIMA_BRUTA, MONEDA,
            TIPO_MOVIMIENTO, ORIGEN_ERROR, TIPO_SEGURO AS CODIGO_SEGURO, TIPO_MOVIMIENTO_NUM AS CODIGO_MOVIMIENTO,          
    FROM (
        SELECT DISTINCT *
        FROM `produccion.ERRORES_BN_desgravamen_TC` 
    )   
)
SELECT CODIGO_PRODUCTO, CODIGO_CERTIFICADO, FECHA_CARGA, IDEERROR,
    FECHA_INICIO, FECHA_FIN, PRIMA_BRUTA, MONEDA,
    TIPO_MOVIMIENTO, ORIGEN_ERROR, CODIGO_SEGURO, CODIGO_MOVIMIENTO,
    ROW_NUMBER() OVER (PARTITION BY NUMDOCUMENTO, FECHA_INICIO, FECHA_FIN) AS NRO_ND,
    ROW_NUMBER() OVER (PARTITION BY CODIGO_CERTIFICADO, FECHA_INICIO, FECHA_FIN) AS NRO_C,
    COUNT(*) OVER (PARTITION BY CODIGO_CERTIFICADO) AS CANT_ERRORES,
    ROW_NUMBER() OVER (PARTITION BY CODIGO_CERTIFICADO ORDER BY FECHA_INICIO ASC, FECHA_FIN ASC) AS ORDEN_C,
    ROW_NUMBER() OVER (PARTITION BY NUMDOCUMENTO ORDER BY FECHA_INICIO ASC, FECHA_FIN ASC) AS ORDEN_ND
FROM ERROR_BN


--------------------- CANTIDAD Y MONTOS POR CATEGORIA 1ER ERROR BBVA ----------------

CREATE OR REPLACE TABLE `produccion.ERRORES_BBVA_1er_error` AS
WITH cert_1er_error AS (
  SELECT P.COD_DE_CERTIFICADO AS CERTIFICADO_1ER_ERROR, ENTIDAD,
        P.IDEERROR, E.CATEGORIA_ERROR, P.CANT_ERRORES
  FROM `produccion.ERRORES_BBVA_todos` P
  LEFT JOIN `produccion.Tabla_Errores_SAS_v2` E ON P.IDEERROR= E.IDEERROR
  WHERE ORDEN = 1 
)
SELECT E.ENTIDAD, E.CATEGORIA_ERROR, P.IDEERROR, MONEDA, P.NRO,
        COUNT(*) CANTIDAD, SUM(IF(P.TIPO_MOVIMIENTO_NUM= '4',P.PRIMABRUTACAN,0)) AS TOTAL_PRIMA
FROM cert_1er_error E
LEFT JOIN `produccion.ERRORES_BBVA_todos` P ON E.CERTIFICADO_1ER_ERROR = P.COD_DE_CERTIFICADO
LEFT JOIN `produccion.Tabla_Errores_SAS_v2` T ON P.IDEERROR= T.IDEERROR
GROUP BY E.ENTIDAD, E.CATEGORIA_ERROR, P.IDEERROR, MONEDA, NRO

#========================= CANTIDAD Y MONTOS POR CATEGORIA 1ER ERROR BANCA SEGUROS ==================

CREATE OR REPLACE TABLE `produccion.ERRORES_BS_1er_error` AS
WITH cert_1er_error AS (
  SELECT P.CODIGO_CERTIFICADO AS CERTIFICADO_1ER_ERROR, CODIGO_PRODUCTO,
        P.CODIGO_ERROR, E.CATEGORIA_ERROR, P.CANT_ERRORES
  FROM `produccion.ERRORES_BS_todos` P
  LEFT JOIN `produccion.Tabla_Errores_SAS_v2` E ON P.CODIGO_ERROR = E.CODERROR
  WHERE ORDEN = 1 
)
SELECT E.CODIGO_PRODUCTO, E.CATEGORIA_ERROR, P.CODIGO_ERROR, P.TIPO_MOVIMIENTO, MONEDA, P.NRO,
        COUNT(*) CANTIDAD, SUM(P.PRIMA_BRUTA) AS TOTAL_PRIMA
FROM cert_1er_error E
LEFT JOIN `produccion.ERRORES_BS_todos` P ON E.CERTIFICADO_1ER_ERROR = P.CODIGO_CERTIFICADO
LEFT JOIN `produccion.Tabla_Errores_SAS_v2` T ON P.CODIGO_ERROR= T.CODERROR
GROUP BY E.CODIGO_PRODUCTO, E.CATEGORIA_ERROR, P.CODIGO_ERROR, P.TIPO_MOVIMIENTO, MONEDA, NRO


