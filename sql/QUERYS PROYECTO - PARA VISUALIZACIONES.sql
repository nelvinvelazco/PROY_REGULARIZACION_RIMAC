  UNION ALL
  SELECT * FROM tabla_migracion
  UNION ALL
  SELECT * FROM tabla_otros
  UNION ALL
  SELECT * FROM tabla_multi
  UNION ALL
  SELECT * FROM tabla_proteccion_tarjeta
  UNION ALL
  SELECT * FROM tabla_consumer
)



